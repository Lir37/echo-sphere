const {readFileSync,writeFileSync,mkdirSync,existsSync}=require('node:fs');
const {createHash}=require('node:crypto');
const {dirname,resolve}=require('node:path');
const digest=buffer=>createHash('sha256').update(buffer).digest('hex');
const textDigest=buffer=>digest(buffer.toString('utf8').replaceAll('\r\n','\n'));
const sourceDigest=(file,buffer)=>file.endsWith('.svg')?textDigest(buffer):digest(buffer);
const output='UnityProject/Assets/Resources/EchoSphere/CanvasArt';
const manifestPath=output+'/source-art-manifest.json';
const indexPath='UnityProject/Assets/EchoSphere/Scripts/Presentation/Generated/SourceCanvasArtIndex.cs';
if(process.argv.includes('--check')) {
  const manifest=JSON.parse(readFileSync(manifestPath,'utf8'));
  for(const asset of manifest.assets) {
    if(sourceDigest(asset.source,readFileSync(asset.source))!==asset.sourceSha)throw new Error('Source art changed: '+asset.source);
    if(asset.output&&digest(readFileSync(asset.output))!==asset.outputSha)throw new Error('Canvas art changed: '+asset.output);
  }
  if(textDigest(readFileSync(indexPath))!==manifest.indexSha)throw new Error('Canvas art index changed');
  console.log('Authored Canvas art source/derivative provenance: PASS');process.exit(0);
}
const {chromium}=require(process.env.ECHO_PLAYWRIGHT_PATH||'playwright');
async function main() {
  const browser=await chromium.launch({headless:true,...(process.env.ECHO_ART_BROWSER?{channel:process.env.ECHO_ART_BROWSER}:{})});
  try {
    const page=await browser.newPage();const assets=[];
    const source=readFileSync('src/renderer.ts','utf8');const block=source.match(/const ART_PATHS[^=]*=\s*\{([\s\S]*?)\n\};/)[1];
    const paths=[...new Set([...block.matchAll(/:\s*'(\/art\/[^']+)'/g)].map(match=>match[1]))];
    for(const url of paths) {
      const file='public'+url;const bytes=readFileSync(file);const svg=file.endsWith('.svg');
      const data='data:'+(svg?'image/svg+xml':'image/png')+';base64,'+bytes.toString('base64');
      const result=await page.evaluate(async data=> {
        const image=new Image();image.src=data;try{await image.decode();}catch{return {loaded:false,width:0,height:0};}
        const canvas=document.createElement('canvas');canvas.width=image.naturalWidth*4;canvas.height=image.naturalHeight*4;
        const ctx=canvas.getContext('2d');ctx.drawImage(image,0,0,canvas.width,canvas.height);
        const pixels=ctx.getImageData(0,0,canvas.width,canvas.height).data;let visiblePixels=0;for(let i=3;i<pixels.length;i+=4)if(pixels[i]>0)visiblePixels++;
        return {loaded:true,width:image.naturalWidth,height:image.naturalHeight,visiblePixels,png:canvas.toDataURL('image/png').split(',')[1]};
      },data);
      const asset={url,source:file,sourceSha:sourceDigest(file,bytes),loaded:result.loaded,width:result.width,height:result.height,visiblePixels:result.visiblePixels||0};
      if(result.loaded) {
        asset.resource='EchoSphere/CanvasArt/'+url.slice(5).replace(/\.[^.]+$/,'');asset.output='UnityProject/Assets/Resources/'+asset.resource+'.png';
        mkdirSync(dirname(asset.output),{recursive:true});const png=Buffer.from(result.png,'base64');writeFileSync(asset.output,png);asset.outputSha=digest(png);
      }
      assets.push(asset);
    }
    const quote=JSON.stringify;
    const code='#if UNITY_EDITOR && ECHO_SPHERE_REFERENCE_VISUALS\n// Generated by rendering the unchanged source images in the reference Canvas implementation.\nusing System.Collections.Generic;\nnamespace EchoSphere.Presentation { public static class SourceCanvasArtIndex { public static readonly Dictionary<string,string> Resources=new Dictionary<string,string> {\n'+assets.filter(a=>a.loaded).map(a=>'{'+quote(a.url)+','+quote(a.resource)+'}').join(',\n')+'\n}; public static readonly Dictionary<string,double[]> Dimensions=new Dictionary<string,double[]> {\n'+assets.map(a=>'{'+quote(a.url)+',new double[]{'+a.width+'d,'+a.height+'d}}').join(',\n')+'\n}; } }\n\n#endif\n';
    writeFileSync(indexPath,code);mkdirSync(output,{recursive:true});writeFileSync(manifestPath,JSON.stringify({renderer:await browser.version(),rasterScale:4,assets,indexSha:digest(Buffer.from(code))},null,2)+'\n');
    console.log(`Source art: ${assets.filter(a=>a.loaded).length} original images rasterized; ${assets.filter(a=>!a.loaded).length} original decode failures preserved.`);
  } finally {await browser.close();}
}
main().catch(error=>{console.error(error);process.exitCode=1;});
